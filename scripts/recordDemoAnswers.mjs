// Records the demo mode answers. Run it with the app already running locally
// against the real Gemini key:
//
//   npm run dev                                   (in one terminal)
//   node scripts/recordDemoAnswers.mjs            (in another)
//
// It sends each sample sentence to the local helper, takes the JSON the helper
// returns, and writes lib/demo/recordedAnswers.ts. Nobody edits that file by
// hand: to change a sample or re-record, change SAMPLES here and run this again.
//
// If the helper asks for an access code, put it in JUDGE_ACCESS_CODE in the
// shell that runs this script. It is sent as a header and never written anywhere.

import { mkdir, readFile, writeFile } from "node:fs/promises";

const BASE_URL = process.env.RECORD_BASE_URL ?? "http://localhost:3000";
const OUTPUT = new URL("../lib/demo/recordedAnswers.ts", import.meta.url);
const GEMINI_FILE = new URL("../lib/server/gemini.ts", import.meta.url);

const SAMPLES = [
  "So I start with about a pound of ground beef, then a handful of breadcrumbs and two eggs.",
  "Add a pinch of salt and a splash of milk, and mix it all with your hands until it feels right.",
  "Oh, the kids are home early, so put the oven on to 350 and hand me that big bowl. Now a cup of flour, two tablespoons of sugar and a little butter, and tell your father dinner is at six.",
];

async function askHelper(newText) {
  const headers = { "Content-Type": "application/json" };
  if (process.env.JUDGE_ACCESS_CODE) headers["x-access-code"] = process.env.JUDGE_ACCESS_CODE;

  const response = await fetch(`${BASE_URL}/api/understand`, {
    method: "POST",
    headers,
    body: JSON.stringify({ newText, knownIngredients: [] }),
  });
  const body = await response.json().catch(() => null);
  if (!response.ok) throw new Error(`The helper answered ${response.status}: ${JSON.stringify(body)}`);
  return body;
}

async function modelName() {
  const source = await readFile(GEMINI_FILE, "utf8");
  return source.match(/GEMINI_MODEL = "([^"]+)"/)?.[1] ?? "unknown model";
}

const recorded = {};
for (const sample of SAMPLES) {
  console.log(`Recording: ${sample}`);
  recorded[sample] = await askHelper(sample);
}

const file = `// Recorded Gemini answers for the three demo sentences.
// GENERATED by scripts/recordDemoAnswers.mjs on ${new Date().toISOString().slice(0, 10)} with ${await modelName()}.
// Do not edit by hand: change the samples in the script and record again.

import type { UnderstandAnswer } from "../types";

export const SAMPLE_SENTENCES: string[] = ${JSON.stringify(SAMPLES, null, 2)};

export const RECORDED_ANSWERS: Record<string, UnderstandAnswer> = ${JSON.stringify(recorded, null, 2)};
`;

await mkdir(new URL("./", OUTPUT), { recursive: true });
await writeFile(OUTPUT, file);
console.log(`Wrote ${OUTPUT.pathname}`);
